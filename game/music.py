_SRC_HASH = None


def _src_hash():
    global _SRC_HASH
    if _SRC_HASH is None:
        try:
            with open(__file__, "rb") as f:
                _SRC_HASH = hashlib.md5(f.read()).hexdigest()[:10]
        except OSError:
            _SRC_HASH = "nosrc"
    return _SRC_HASH


def cache_dir():
    d = os.environ.get("RR_MUSIC_CACHE")
    if not d:
        from game import settings
        d = os.path.join(os.path.dirname(os.path.abspath(settings.SETTINGS_PATH)), "music_cache")
    return d


def cache_path(zone, rate=RATE):
    spec = TRACKS[zone]
    h = hashlib.md5((_src_hash() + repr(sorted(spec.items())) + str(rate)).encode()).hexdigest()[:12]
    return os.path.join(cache_dir(), f"{zone}_{h}_{rate}.wav")


def wav_bytes(pcm, rate=RATE):
    bio = io.BytesIO()
    with wave.open(bio, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(pcm)
    return bio.getvalue()


def load_or_render(zone, rate=RATE):
    """WAV bytes for `zone`, from the disk cache or freshly rendered (and cached)."""
    path = cache_path(zone, rate)
    try:
        with open(path, "rb") as f:
            return f.read()
    except OSError:
        pass
    data = wav_bytes(compose_and_render(TRACKS[zone], rate), rate)
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "wb") as f:
            f.write(data)
        os.replace(tmp, path)
    except OSError:
        pass  # read-only install - just re-render next launch
    return data


# ------------------------------------------------------ background worker

class Library:
    """Thread-safe front for the game loop: request(zone) returns WAV bytes if the
    track is ready, otherwise schedules it (front of the queue) and returns None
    immediately. A single daemon worker then pre-renders every other track in the
    background so later zone changes are instant."""

    def __init__(self, rate=RATE, prewarm=True):
        self.rate = rate
        self._ready = {}
        self._queue = []
        self._lock = threading.Lock()
        self._wake = threading.Event()
        self._thread = None
        self._prewarm = prewarm

    def request(self, zone):
        if zone not in TRACKS:
            return None
        with self._lock:
            data = self._ready.get(zone)
            if data is not None:
                return data
            if zone in self._queue:
                self._queue.remove(zone)
            self._queue.insert(0, zone)
            if self._prewarm and len(self._queue) == 1 and not self._ready:
                self._queue += [z for z in TRACKS if z != zone]
        self._ensure_thread()
        self._wake.set()
        return None

    def is_ready(self, zone):
        with self._lock:
            return zone in self._ready

    def _ensure_thread(self):
        if self._thread is None or not self._thread.is_alive():
            self._thread = threading.Thread(target=self._run, name="music-render", daemon=True)
            self._thread.start()

    def _run(self):
        while True:
            with self._lock:
                zone = next((z for z in self._queue if z not in self._ready), None)
                if zone is not None:
                    self._queue.remove(zone)
            if zone is None:
                self._wake.wait(1.0)
                self._wake.clear()
                continue
            try:
                data = load_or_render(zone, self.rate)
            except Exception:  # music must never crash the game
                data = None
            if data is not None:
                with self._lock:
                    self._ready[zone] = data


class Hysteresis:
    """Stable choice from a jittery candidate (e.g. the biome under the player):
    the value only changes after the new candidate has held for `dwell` seconds,
    so walking along a border doesn't flip-flop between two things."""

    def __init__(self, dwell=2.0):
        self.dwell = dwell
        self.value = None
        self._cand = None
        self._t = 0.0

    def update(self, dt, candidate):
        if self.value is None:
            self.value = candidate
            return self.value
        if candidate == self.value:
            self._cand, self._t = None, 0.0
            return self.value
        if candidate != self._cand:
            self._cand, self._t = candidate, 0.0
        self._t += dt
        if self._t >= self.dwell:
            self.value, self._cand, self._t = candidate, None, 0.0
        return self.value

    def reset(self, value=None):
        self.value, self._cand, self._t = value, None, 0.0
