"""
Zone music: one ~60 second, seamlessly looping, ORIGINAL 8-bit rock track per
zone (Nexus, Bazaar, Vault, the 10 Realm biomes, the 2 island themes and every
dungeon theme incl. the Forge).

Every song is composed procedurally from a small data spec (key, scale,
tempo, groove style, chord progressions per section and a melody seed) - the
melodies are generated by a seeded random walk over the scale with
chord-tone targeting, so nothing here reproduces any existing song. The same
toolkit the old themes used (square/pulse lead, root+fifth power chords,
triangle bass, noise kick/snare/hi-hat) - just rendered much faster:

* each note is a repeated single-cycle wavetable (bytes * n, C speed) with a
  segment-wise envelope applied through audioop.mul, and every note/drum is
  mixed into the song buffer with audioop.add (saturating, C speed) - a full
  minute renders in well under a second instead of the old per-sample Python
  loops;
* songs are rendered CIRCULARLY: the ringing tail of the last bar is folded
  back onto the first samples, so the loop point is a perfectly continuous,
  bar-aligned seam (no click, no gap);
* rendered tracks are cached to disk as .wav (music_cache/, keyed by a hash of
  this file + the spec + the sample rate, so editing a song invalidates only
  that cache entry) and rendered on a background worker thread - the game
  loop never waits for music (see request()).

RR_NO_MUSIC=1 (set by tests/run_all_checks.py) turns the background worker
and playback off; render() itself still works for tests.
"""
